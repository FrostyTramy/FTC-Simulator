using System.Security;

namespace Sim.Editor;

/// <summary>
/// The project the language server sees (spec 07 "Project model"): an Eclipse project in the app's own folder (never
/// inside the team's repository) whose source folder is a link to the team's TeamCode/src/main/java and whose classpath
/// is the SDK shim jar (with sources, for javadoc and go-to-definition) and Java 17, exactly what the sim build compiles
/// against.
/// </summary>
public sealed class EclipseProject
{
    private EclipseProject(string directory, string sourceDir)
    {
        Directory = directory;
        SourceDir = sourceDir;
    }

    /// <summary>Folder with .project and .classpath.</summary>
    public string Directory { get; }

    /// <summary>The team's TeamCode/src/main/java (linked, not copied).</summary>
    public string SourceDir { get; }

    /// <summary>Writes (or refreshes) the project files.</summary>
    /// <param name="name">Project name, e.g. the repository folder name.</param>
    /// <param name="directory">Where to write (app data, outside the repository).</param>
    /// <param name="teamCodeJavaDir">TeamCode/src/main/java of the team's repository.</param>
    public static EclipseProject Create(string name, string directory, string teamCodeJavaDir, string shimJar, string? shimSourcesJar)
    {
        System.IO.Directory.CreateDirectory(Path.Combine(directory, ".settings"));
        var source = Path.GetFullPath(teamCodeJavaDir);
        File.WriteAllText(Path.Combine(directory, ".project"), $"""
            <?xml version="1.0" encoding="UTF-8"?>
            <projectDescription>
              <name>{Xml(name)}</name>
              <comment>Generated by the FTC simulator for the Java language server. Do not edit.</comment>
              <buildSpec>
                <buildCommand><name>org.eclipse.jdt.core.javabuilder</name></buildCommand>
              </buildSpec>
              <natures><nature>org.eclipse.jdt.core.javanature</nature></natures>
              <linkedResources>
                <link><name>TeamCode</name><type>2</type><location>{Xml(source.Replace('\\', '/'))}</location></link>
              </linkedResources>
            </projectDescription>
            """);
        var sources = shimSourcesJar != null ? $" sourcepath=\"{Xml(shimSourcesJar.Replace('\\', '/'))}\"" : "";
        File.WriteAllText(Path.Combine(directory, ".classpath"), $"""
            <?xml version="1.0" encoding="UTF-8"?>
            <classpath>
              <classpathentry kind="src" path="TeamCode"/>
              <classpathentry kind="con" path="org.eclipse.jdt.launching.JRE_CONTAINER/org.eclipse.jdt.internal.debug.ui.launcher.StandardVMType/JavaSE-17"/>
              <classpathentry kind="lib" path="{Xml(shimJar.Replace('\\', '/'))}"{sources}/>
              <classpathentry kind="output" path="bin"/>
            </classpath>
            """);
        File.WriteAllText(Path.Combine(directory, ".settings", "org.eclipse.jdt.core.prefs"), """
            eclipse.preferences.version=1
            org.eclipse.jdt.core.compiler.codegen.targetPlatform=17
            org.eclipse.jdt.core.compiler.compliance=17
            org.eclipse.jdt.core.compiler.source=17
            org.eclipse.jdt.core.compiler.release=enabled
            """);
        return new EclipseProject(directory, source);
    }

    private static string Xml(string s) => SecurityElement.Escape(s);
}
